/**
 * AI Slop Checker - Report Export Formatter
 * Generates formatted Markdown and structured JSON summaries.
 */

function formatMarkdownReport(target, analysis) {
  const timestamp = new Date().toISOString();
  const title = (typeof target === 'string' ? target : target.url || target.title) || 'Text Analysis';
  const badgeColor = analysis.score >= 70 ? 'red' : analysis.score >= 40 ? 'orange' : 'green';

  let md = `# AI Slop Inspection Report\n\n`;
  md += `**Target:** ${title}\n`;
  md += `**Date:** ${timestamp}\n`;
  md += `**Verdict:** ![Verdict](https://img.shields.io/badge/Slop_Score-${analysis.score}%25-${badgeColor}) **${analysis.verdict}**\n\n`;
  md += `## Metrics Overview\n\n`;
  md += `| Metric | Value |\n`;
  md += `|:---|:---|\n`;
  md += `| Word Count | ${analysis.wordCount || 0} |\n`;
  md += `| Sentence Count | ${analysis.sentenceCount || 0} |\n`;
  md += `| Lexical Diversity (TTR) | ${analysis.lexicalDiversity ?? 'N/A'} |\n`;
  md += `| Personal Voice | ${analysis.hasFirstPersonVoice ? 'Present' : 'Absent (Abstract)'} |\n`;
  md += `| Passive Voice Matches | ${analysis.passiveVoiceCount || 0} |\n\n`;

  md += `## Detected Cliché & Buzzword Matches\n\n`;
  const highHits = analysis.matchedPhrases?.high || [];
  const midHits = analysis.matchedPhrases?.mid || [];

  if (highHits.length === 0 && midHits.length === 0) {
    md += `*No prominent AI buzzword phrases detected.*\n`;
  } else {
    if (highHits.length > 0) {
      md += `### High Severity Phrases\n`;
      highHits.forEach(h => {
        md += `- **"${h.phrase}"** (occurrences: ${h.count})\n`;
      });
      md += `\n`;
    }
    if (midHits.length > 0) {
      md += `### Moderate Severity Buzzwords\n`;
      midHits.forEach(h => {
        md += `- *"${h.phrase}"* (occurrences: ${h.count})\n`;
      });
      md += `\n`;
    }
  }

  md += `---\n*Generated by AI Slop Checker*\n`;
  return md;
}

function formatJsonReport(target, analysis) {
  return JSON.stringify({
    timestamp: new Date().toISOString(),
    target,
    analysis
  }, null, 2);
}

module.exports = {
  formatMarkdownReport,
  formatJsonReport
};
